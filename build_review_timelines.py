#!/usr/bin/env python3
"""Render data/review-timelines.json into index.html, the site's landing page.

What the review team did to the AI-generated snags on Lagoons - Ibiza
(T240-T245) and Hills - Gems (E511B), read from each snag's change history in QA/QC.
It is laid out like the archived Review Stats page (build_review.py, whose page
rules it shares), with the review's own categories in place of edited fields.

The JSON holds one row per snag and one row per categorised change. Each
change is the snag field's net change, from its issued value to its final
value, so edits that were later undone are already gone, and it is credited to
whoever made the final edit. Only changes by the people in "tracked" are in it,
who appear by their initials because the site is public.

Every material snag gets exactly one outcome: deleted, changed (its
description or type was edited, or it was switched to non-material), or no
change. Priority and trade changes are counted in their own tables, so a snag
whose only change was its priority or trade counts as no change. Only snags
generated by AI ("Auto" in QA/QC) are counted.

index.html used to be the Ibiza time and motion page, and before that the
activity log, so old links (…/#Ibiza-T241, …/#BL515) are sent on to wherever
they live now.
"""

import json
from collections import Counter, defaultdict
from pathlib import Path

import build_review
import build_time_motion
import theme
from theme import GENERATED, esc

ROOT = Path(__file__).parent
DATA_PATH = ROOT / "data" / "review-timelines.json"
SLUG = "review-tl"

# (category, column label, what it records), as the review defined them
CATEGORIES = [
    ("Priority", "Priority", "Urgency changed: low, medium or high"),
    ("Trade", "Trade", "Responsible discipline changed: Civil, MEP, Joinery, Aluminium"),
    ("Material/non-material", "Material → non-material",
     "Switched from a material snag to a non-material one"),
    ("Type update", "Type update",
     "The Type part of the description changed, e.g. Wall - Stains → Door leaf"),
    ("Large description update", "Large description",
     "5 or more words of the title or detail changed, or the title replaced outright"),
    ("Small description update", "Small description", "1 to 4 words of the title or detail changed"),
]
# Priority and trade have their own tables; "changed" counts the other four.
SEPARATE = ("Priority", "Trade")
CONTENT = [c for c in CATEGORIES if c[0] not in SEPARATE]


# ------------------------------------------------------------- arithmetic ---

def num(n):
    return f"{n:,}"


def pct(n, d):
    return f"{100 * n / d:.1f}%" if d else "0.0%"


def tally(data):
    """Per-unit outcome counts over the AI-generated material snags."""
    snags = [dict(zip(("unit", "snag", "status", "kind", "auto"), s)) for s in data["snags"]]
    auto = [s for s in snags if s["auto"]]
    keep = {(s["unit"], s["snag"]) for s in auto}
    changes = [c for c in data["changes"] if (c["unit"], c["snag"]) in keep]
    cats = defaultdict(dict)
    for c in changes:
        cats[(c["unit"], c["snag"])][c["category"]] = c

    def material(s):
        """Issued as a material snag: still material, deleted, or switched by the review."""
        return (s["kind"] == "Material" or s["status"] == "Deleted"
                or "Material/non-material" in cats[(s["unit"], s["snag"])])

    content = {k for k, _, _ in CONTENT}
    rows = []
    for u in data["units"]:
        mat = [s for s in auto if s["unit"] == u["key"] and material(s)]
        kept = [s for s in mat if s["status"] != "Deleted"]
        rows.append({
            "unit": u, "snags": len(mat), "deleted": len(mat) - len(kept),
            "changed": sum(1 for s in kept if set(cats[(s["unit"], s["snag"])]) & content),
            "cat": Counter(c for s in kept for c in cats[(s["unit"], s["snag"])] if c != "Deletion"),
        })
    total = {"unit": {"key": "Total", "label": "Total"},
             **{k: sum(v[k] for v in rows) for k in ("snags", "deleted", "changed")},
             "cat": sum((v["cat"] for v in rows), Counter())}
    for v in rows + [total]:
        v["none"] = v["snags"] - v["deleted"] - v["changed"]
        if v["none"] < 0:
            raise SystemExit(f'{v["unit"]["label"]}: deleted and changed exceed its material snags')
    nonmat = [s for s in auto if s["kind"] == "Non material"]
    switched = [s for s in nonmat if "Material/non-material" in cats[(s["unit"], s["snag"])]]
    kept_keys = {(s["unit"], s["snag"]) for s in auto if material(s) and s["status"] != "Deleted"}
    deleted_keys = {(s["unit"], s["snag"]) for s in auto if s["status"] == "Deleted"}
    return {"rows": rows, "total": total, "cats": cats, "changes": changes, "nonmat": nonmat,
            "switched": switched, "kept": kept_keys, "deleted": deleted_keys,
            "by_hand": len(snags) - len(auto)}


# --------------------------------------------------------------- rendering ---

def meter(n, d, what, label, cls=""):
    """A share as a bar with its percentage, like the '% snags changed' column."""
    p = 100 * n / d if d else 0
    return f"""<td class="meter">
          <span class="mtrack"><i{f' class="{cls}"' if cls else ""} style="width:{p:.2f}%"
            title="{esc(label)}: {num(n)} of {num(d)} snags {what}"></i></span>
          <span class="mval mono">{p:.1f}%</span>
        </td>"""


def unit_link(u):
    page = build_time_motion.page_file("tm-ibiza" if u["tm"].startswith("Ibiza") else "tm-gems")
    return (f'<a class="sunit mono" href="{page}#{esc(u["tm"])}" '
            f'title="Open {esc(u["label"])} in pilot time and motion">{esc(u["label"])}</a>')


def render_scope(t, tracked):
    rows = "".join(f"""
      <tr><th class="mono">{esc(v["unit"]["label"])}</th>
        <td class="num">{num(v["snags"])}</td></tr>""" for v in t["rows"])
    T = t["total"]
    return f"""
<article class="card">
  <div class="card-head">
    <h2>Scope</h2>
    <p class="card-sub">For each unit, how many of the snags were deleted, how many were changed, and how many had no change. It covers the snags generated by AI (Created by &ldquo;Auto&rdquo;) on five Lagoons &ndash; Ibiza units and one Hills &ndash; Gems unit.</p>
  </div>
  <div class="scope-cols">
    <div class="tblwrap narrow">
      <table class="dt">
        <thead><tr><th>Unit</th><th class="num">Material snags</th></tr></thead>
        <tbody>{rows}</tbody>
        <tfoot><tr><th class="mono">Total</th>
          <td class="num">{num(T["snags"])}</td></tr></tfoot>
      </table>
    </div>
    <div class="prose">
      <p class="lede">Every figure in this report is counted over the {num(T["snags"])} AI-generated material snags only. The {num(t["by_hand"])} snags added by hand are left out.</p>
      <h3>What each term means</h3>
      <p>Every material snag has exactly one outcome: it was deleted, it was changed (its description or type was edited, or it was switched to non-material), or it had no change. Priority and trade changes are counted separately, so a snag whose only change was its priority or trade counts as no change. Only changes made by the review team ({" and ".join(f"<b>{esc(p)}</b>" for p in tracked)}) count, and each snag is judged on where it ended up compared with how it was issued, so edits that were later undone do not count.</p>
      <h3>The denominator</h3>
      <p>Every percentage in this report uses the same denominator: the <b>material snags issued for that unit</b>. That includes the {len(t["switched"])} snags the review switched to non-material. The other {num(len(t["nonmat"]) - len(t["switched"]))} non-material snags sit outside it.</p>
      <p class="eq mono">{num(T["deleted"])} deleted + {num(T["changed"])} changed + {num(T["none"])} no change
        = {num(T["snags"])}</p>
    </div>
  </div>
</article>"""


def render_outcomes(t):
    peak = max(v["snags"] for v in t["rows"])
    words = {"deleted": "deleted", "changed": "changed", "none": "no change"}
    rows = []
    for v in t["rows"]:
        label = v["unit"]["label"]
        segs = "".join(
            f'<i class="seg {cls}" style="flex:{v[k]}" title="{esc(label)}: {num(v[k])} {words[k]} '
            f'({pct(v[k], v["snags"])})"></i>'
            for k, cls in (("deleted", "deleted"), ("changed", "changed"), ("none", "untouched")) if v[k] > 0)
        rows.append(f"""
    <div class="srow">
      {unit_link(v["unit"])}
      <div class="strack">
        <div class="sbar" style="width:{100 * v["snags"] / peak:.3f}%">{segs}</div>
        <span class="slab mono">{num(v["snags"])}</span>
      </div>
      <div class="sout">
        <span class="o deleted mono">{num(v["deleted"])}</span>
        <span class="o changed mono">{num(v["changed"])}</span>
        <span class="o untouched mono">{num(v["none"])}</span>
      </div>
    </div>""")
    T = t["total"]
    legend = (f'<span><i class="sw deleted"></i>Deleted <b class="mono">{num(T["deleted"])}</b></span>'
              f'<span><i class="sw changed"></i>Changed <b class="mono">{num(T["changed"])}</b></span>'
              f'<span><i class="sw untouched"></i>No change <b class="mono">{num(T["none"])}</b></span>')
    return f"""
<article class="card">
  <div class="card-head">
    <h2>What the review did with each unit's snags</h2>
    <p class="card-sub">Bar length is the unit's material snag count, split into the three
    outcomes. Changed means the description or type was edited, or the snag was switched to non-material. Priority and trade changes are shown separately below. Unit names link through to pilot time and motion.</p>
  </div>
  <div class="legend">{legend}</div>
  <div class="chart">{"".join(rows)}</div>
</article>"""


def render_share(t, title, sub, col, head, what, count, cls="", extra=""):
    """One count per unit as a share of its material snags, with a bar: the
    deletions, priority and trade tables."""
    rows = "".join(f"""
      <tr><th class="mono">{esc(v["unit"]["label"])}</th>
        <td class="num">{num(v["snags"])}</td>
        <td class="num">{num(count(v))}</td>
        {meter(count(v), v["snags"], what, v["unit"]["label"], cls)}</tr>""" for v in t["rows"])
    T = t["total"]
    rates = sorted(t["rows"], key=lambda v: count(v) / v["snags"])
    lo, hi = rates[0], rates[-1]
    return f"""
<article class="card">
  <div class="card-head">
    <h2>{title}</h2>
    <p class="card-sub">{sub}</p>
  </div>
  <div class="tblwrap">
    <table class="dt">
      <thead><tr><th>Unit</th><th class="num">Material</th><th class="num">{col}</th>
        <th class="num wide">{head}</th></tr></thead>
      <tbody>{rows}</tbody>
      <tfoot><tr><th class="mono">Total</th>
        <td class="num">{num(T["snags"])}</td>
        <td class="num">{num(count(T))}</td>
        {meter(count(T), T["snags"], what, "Total", cls)}</tr></tfoot>
    </table>
  </div>
  <p class="after">The rate ranges from {pct(count(lo), lo["snags"])} on {esc(lo["unit"]["label"])} to {pct(count(hi), hi["snags"])} on {esc(hi["unit"]["label"])}.{(" " + extra) if extra else ""}</p>
</article>"""


def kept_changes(t, category):
    return [c for c in t["changes"] if c["category"] == category and (c["unit"], c["snag"]) in t["kept"]]


def moves(rows):
    return ", ".join(f"{m} ({num(n)})" for m, n in Counter(f'{c["from"]} → {c["to"]}' for c in rows).most_common())


def render_priority(t):
    rank = {"low": 0, "medium": 1, "high": 2}
    rows = kept_changes(t, "Priority")
    lowered = sum(1 for c in rows if rank[c["to"]] < rank[c["from"]])
    return render_share(
        t, "Priority changes", "Snags whose priority the review changed, as a share of material snags.",
        "Priority changed", "% changed", "with a priority change", lambda v: v["cat"]["Priority"],
        extra=f"Of the {num(len(rows))}, {num(lowered)} lowered the priority and {num(len(rows) - lowered)} "
              f"raised it: {esc(moves(rows))}.")


def render_trade(t):
    return render_share(
        t, "Trade changes", "Snags moved to a different trade by the review, as a share of material snags.",
        "Trade changed", "% changed", "with a trade change", lambda v: v["cat"]["Trade"],
        extra=f"The moves were {esc(moves(kept_changes(t, 'Trade')))}.")


def render_changes(t):
    def cell(v, k):
        n = v["cat"][k]
        sub = f'<span class="sub">{pct(n, v["snags"])}</span>' if n else ""
        return f'<td class="num">{num(n)}{sub}</td>'

    def row(v):
        return f"""
      <tr><th class="mono">{esc(v["unit"]["label"])}</th>
        <td class="num">{num(v["snags"])}</td>
        {"".join(cell(v, k) for k, _, _ in CONTENT)}
        <td class="num">{num(v["changed"])}</td>
        {meter(v["changed"], v["snags"], "changed", v["unit"]["label"])}</tr>"""

    defs = "".join(f"""
      <tr><th>{esc(label)}</th><td class="wrap">{esc(what)}</td></tr>""" for _, label, what in CONTENT)
    heads = "".join(f'<th class="num">{esc(label)}</th>' for _, label, _ in CONTENT)
    return f"""
<article class="card">
  <div class="card-head">
    <h2>Changes by category</h2>
    <p class="card-sub">Every change to a kept snag's description or type, and every switch to non-material, falls into one of four categories. Priority and trade changes are shown in their own tables above.</p>
  </div>
  <div class="tblwrap narrow">
    <table class="dt">
      <thead><tr><th>Category</th><th>What it records</th></tr></thead>
      <tbody>{defs}</tbody>
    </table>
  </div>
  <p class="between">A snag gets at most one of the three description categories: a type update outranks a large description update, which outranks a small one. Each cell is the number of snags in that category, with its share of the unit's material snags in brackets. The last column is the share of the unit's snags changed in any of these four categories (i.e. one category or more).</p>
  <div class="tblwrap">
    <table class="dt">
      <thead><tr><th>Unit</th><th class="num">Material</th>{heads}
        <th class="num">Changed</th><th class="num wide">% snags changed</th></tr></thead>
      <tbody>{"".join(row(v) for v in t["rows"])}</tbody>
      <tfoot>{row(t["total"])}</tfoot>
    </table>
  </div>
  <p class="after">A snag can change in more than one category, so the category columns sum to more than the changed column.</p>
</article>"""


def render_people(t, data):
    """Changes credited to whoever made the final edit: deletions on deleted
    snags, every other category on kept snags."""
    labels = {u["key"]: u["label"] for u in data["units"]}
    order = [u["key"] for u in data["units"]]
    count = {p: Counter() for p in data["tracked"]}
    for c in t["changes"]:
        key = (c["unit"], c["snag"])
        if c["category"] == "Deletion" and key in t["deleted"]:
            count[c["by"]]["Deletion"] += 1
        elif c["category"] != "Deletion" and key in t["kept"]:
            count[c["by"]][c["category"]] += 1
    cols = [("Deletion", "Deleted")] + [(k, label) for k, label, _ in CATEGORIES]
    heads = "".join(f'<th class="num">{esc(label)}</th>' for _, label in cols)

    def row(name, c):
        worked = sorted({x["unit"] for x in t["changes"] if x["by"] == name}, key=order.index) if name else []
        sub = f'<span class="sub">{esc(", ".join(labels[u] for u in worked))}</span>' if worked else ""
        return (f'<tr><th>{esc(name or "Total")}{sub}</th>'
                + "".join(f'<td class="num">{num(c[k])}</td>' for k, _ in cols)
                + f'<td class="num">{num(sum(c[k] for k, _ in cols))}</td></tr>')

    return f"""
<article class="card">
  <div class="card-head">
    <h2>Changes by person</h2>
    <p class="card-sub">Who made each change, credited to whoever made its final edit, with the units they worked on.</p>
  </div>
  <div class="tblwrap">
    <table class="dt">
      <thead><tr><th>Person</th>{heads}<th class="num">Total</th></tr></thead>
      <tbody>{"".join(row(p, count[p]) for p in data["tracked"])}</tbody>
      <tfoot>{row(None, sum(count.values(), Counter()))}</tfoot>
    </table>
  </div>
  <p class="after">Deleted counts the snags each person deleted. The other columns count snags that were kept.</p>
</article>"""


def render_examples(t, data):
    """One snag per type of edit: the snag as issued beside where the review left it."""
    labels = {u["key"]: u["label"] for u in data["units"]}
    order = ["location", "trade", "type", "kind", "description"]
    names = {"location": "Location", "trade": "Trade", "type": "Type",
             "kind": "Material or non-material", "description": "Description"}
    cards = []
    for unit, snag, tag in data["examples"]:
        d, cats = data["details"][f"{unit} {snag}"], t["cats"][(unit, snag)]
        desc = next((c for k, c in cats.items() if k.endswith("update")), None)
        before = [p.strip() for p in desc["from"].split(";")] if desc else None
        after = [p.strip() for p in desc["to"].split(";")] if desc else None
        issued = {"location": d["location"], "trade": cats["Trade"]["from"] if "Trade" in cats else d["trade"],
                  "type": before[0] if before else d["type"], "kind": "Material",
                  "description": before[1] if before else d["title"]}
        edited = {"location": d["location"], "trade": d["trade"],
                  "type": after[0] if after else d["type"],
                  "kind": "Non material" if "Material/non-material" in cats else "Material",
                  "description": after[1] if after else d["title"]}
        diff = [k for k in order if issued[k] != edited[k]]
        who = next(iter(cats.values()))["by"]

        def side(src, cls, title):
            rows = "".join(f'<div class="ex-f{" is-diff" if k in diff else ""}">'
                           f'<dt>{names[k]}</dt><dd>{esc(src[k])}</dd></div>' for k in order)
            return f'<div class="ex-side {cls}"><h4>{title}</h4><dl class="ex-dl">{rows}</dl></div>'

        cards.append(f"""
<article class="card ex">
  <div class="ex-head">
    <h3><span class="mono">{esc(labels[unit])} &middot; {esc(snag)}</span> <span class="ex-who">by {esc(who)}</span></h3>
    <span class="ex-tag">{esc(tag)}</span>
  </div>
  <div class="ex-body">
    <div class="ex-cols">{side(issued, "is-ai", "AI output")}{side(edited, "is-man", "Manual edit")}</div>
  </div>
</article>""")
    return f"""
<div class="card-head sec-head">
  <h2>Example changes</h2>
  <p class="card-sub">One snag for each type of edit, read from its change history: the snag as issued beside where the review left it. The edited fields are marked on both sides.</p>
</div>
<div class="exgrid">{"".join(cards)}</div>"""


def forward_old_links():
    """Old links into index.html (…/#Ibiza-T241 from time and motion, …/#BL515
    from the activity log) go on to the page that now has them."""
    pages = {u["slug"]: build_time_motion.page_file(u["site"]) for u in build_time_motion.read_units()}
    known = ",".join(f'"{s}":"{p}"' for s, p in sorted(pages.items()))
    return f"""<script>
/* index.html used to be time and motion (…/#Ibiza-T241) and the activity log (…/#BL515). Send them on. */
(function(){{
  var h = decodeURIComponent(location.hash.slice(1)).replace(/^u-/, '');
  var pages = {{{known}}};
  if (h) location.replace((pages[h] || '{build_time_motion.page_file("activity")}') + location.hash);
}})();
</script>"""


def render(data):
    t = tally(data)
    T = t["total"]
    share = {k: pct(T[k], T["snags"]) for k in ("deleted", "changed", "none")}
    strip = "".join(f'<div><span class="k">{k}</span><span class="v mono">{v}</span>'
                    f'<span class="s">{s}</span></div>' for k, v, s in [
        ("Units reviewed", str(len(t["rows"])), "in this report"),
        ("AI material snags", num(T["snags"]), "every figure counts over these"),
        ("Deleted", num(T["deleted"]), f'{share["deleted"]}, removed from the board'),
        ("Changed", num(T["changed"]), f'{share["changed"]}, kept but edited'),
        ("No change", num(T["none"]), f'{share["none"]}, apart from priority or trade'),
        ("AI non-material snags", num(len(t["nonmat"])), f'{len(t["switched"])} switched from material by the review'),
    ])
    masthead = theme.masthead(
        SLUG, "Review Stats",
        f'Across six units, {num(T["deleted"])} of the {num(T["snags"])} AI-generated material snags were '
        f'deleted ({share["deleted"]}), {num(T["changed"])} were changed ({share["changed"]}), and '
        f'{num(T["none"])} had no change ({share["none"]}). Separately, the priority changed on '
        f'{num(T["cat"]["Priority"])} ({pct(T["cat"]["Priority"], T["snags"])}) and the trade on '
        f'{num(T["cat"]["Trade"])} ({pct(T["cat"]["Trade"], T["snags"])}).',
        f"Source <b>{esc(data['source']['doc'])}</b><br>Units <b>{len(t['rows'])}</b> &middot; Read "
        f"<b>{esc(data['source']['read'])}</b><br>Generated <b>{GENERATED:%d %b %Y}</b>")

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>DAMAC snagging pilot &mdash; review stats</title>
<meta name="description" content="What the review deleted and changed across Ibiza T240&ndash;T245 and Hills Gems E511B, from each snag's change history.">
{forward_old_links()}
<style>
{theme.CHROME_CSS}

{build_review.PAGE_CSS}
.ex-who{{font-size:12px;font-weight:500;color:var(--muted);letter-spacing:0}}
.mtrack i.del{{background:var(--c-del)}}
.sunit{{flex:0 0 235px}}
.scope-cols{{grid-template-columns:minmax(320px,400px) 1fr}}
@media (max-width:720px){{.sunit{{flex:0 0 auto}}}}
</style>
</head>
<body>
<div class="wrap">

{masthead}

<div class="strip">{strip}</div>

{render_scope(t, data["tracked"])}

{render_outcomes(t)}

{render_share(t, "Deletions", "Snags removed from the board, as a share of material snags.", "Deleted", "% deleted", "deleted", lambda v: v["deleted"], cls="del")}

{render_priority(t)}

{render_trade(t)}

{render_changes(t)}

{render_people(t, data)}

{render_examples(t, data)}

</div>
</body>
</html>
"""


def main():
    data = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    out = ROOT / build_time_motion.page_file(SLUG)
    out.write_text(render(data), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size:,} bytes) for {len(data['units'])} units")


if __name__ == "__main__":
    main()
